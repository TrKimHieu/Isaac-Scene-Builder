"""
nav_export.py - Robot spawn + waypoints -> ROS 2 Nav2 files next to the BEV map.

map_data["robot"] = {"spawn": {"x", "y", "yaw"(deg)}, "waypoints": [[x, y], ...]}
(USD world meters; the BEV PGM/YAML map frame == the USD world frame).

Writes into output/bev/<stem>/:
    <stem>_nav.yaml          initial pose + waypoints (map frame, yaw in radians)
    follow_waypoints.py      nav2_simple_commander script: set the initial pose and follow
                             the waypoints on a running Nav2 stack with this map
"""
import math
import os

SCRIPT = '''#!/usr/bin/env python3
"""Follow the waypoints of {nav} with Nav2 (generated by Isaac Scene Builder).

    ros2 launch nav2_bringup bringup_launch.py map:=<this dir>/{map} use_sim_time:=True
    python3 follow_waypoints.py
"""
import math
import os

import rclpy
import yaml
from geometry_msgs.msg import PoseStamped
from nav2_simple_commander.robot_navigator import BasicNavigator, TaskResult

HERE = os.path.dirname(os.path.abspath(__file__))


def pose(nav, p):
    ps = PoseStamped()
    ps.header.frame_id = "map"
    ps.header.stamp = nav.get_clock().now().to_msg()
    ps.pose.position.x, ps.pose.position.y = float(p["x"]), float(p["y"])
    ps.pose.orientation.z = math.sin(p.get("yaw", 0.0) / 2.0)
    ps.pose.orientation.w = math.cos(p.get("yaw", 0.0) / 2.0)
    return ps


def main():
    with open(os.path.join(HERE, "{nav}"), encoding="utf-8") as fh:
        cfg = yaml.safe_load(fh)
    rclpy.init()
    nav = BasicNavigator()
    if cfg.get("initial_pose"):
        nav.setInitialPose(pose(nav, cfg["initial_pose"]))
    nav.waitUntilNav2Active()
    nav.followWaypoints([pose(nav, w) for w in cfg.get("waypoints", [])])
    while not nav.isTaskComplete():
        fb = nav.getFeedback()
        if fb:
            print("waypoint %d/%d" % (fb.current_waypoint + 1, len(cfg["waypoints"])))
    print("result:", {{TaskResult.SUCCEEDED: "succeeded", TaskResult.CANCELED: "canceled",
                       TaskResult.FAILED: "failed"}}.get(nav.getResult(), "unknown"))
    rclpy.shutdown()


if __name__ == "__main__":
    main()
'''


def nav_plan(robot):
    """(initial_pose dict | None, [waypoint dicts]) with yaw in radians; each waypoint
    heads towards the next one (the last keeps the previous heading)."""
    robot = robot or {}
    sp = robot.get("spawn")
    init = None
    if sp:
        init = {"x": float(sp["x"]), "y": float(sp["y"]),
                "yaw": math.radians(float(sp.get("yaw", 0.0)))}
    pts = [(float(p[0]), float(p[1])) for p in robot.get("waypoints") or []]
    wps = []
    prev = (init["x"], init["y"]) if init else None
    yaw = init["yaw"] if init else 0.0
    for k, (x, y) in enumerate(pts):
        nxt = pts[k + 1] if k + 1 < len(pts) else None
        if nxt:
            yaw = math.atan2(nxt[1] - y, nxt[0] - x)
        elif prev:
            yaw = math.atan2(y - prev[1], x - prev[0])
        wps.append({"x": x, "y": y, "yaw": yaw})
        prev = (x, y)
    return init, wps


def write_nav(map_data, scene_dir, stem, map_yaml=None):
    """Write <stem>_nav.yaml + follow_waypoints.py; None when the map has no robot data.
    map_yaml: map_server YAML to use (default <stem>.yaml; the height-sliced map if any)."""
    init, wps = nav_plan(map_data.get("robot"))
    if init is None and not wps:
        return None
    nav_name = stem + "_nav.yaml"
    lines = ["# Robot start + waypoints in the map frame (== USD world frame), yaw in rad.",
             "frame_id: map", "map: %s" % (map_yaml or stem + ".yaml")]
    if init:
        lines.append("initial_pose: {x: %.4f, y: %.4f, yaw: %.4f}" % (
            init["x"], init["y"], init["yaw"]))
    lines.append("waypoints:" if wps else "waypoints: []")
    for w in wps:
        lines.append("  - {x: %.4f, y: %.4f, yaw: %.4f}" % (w["x"], w["y"], w["yaw"]))
    path = os.path.join(scene_dir, nav_name)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    with open(os.path.join(scene_dir, "follow_waypoints.py"), "w", encoding="utf-8") as fh:
        fh.write(SCRIPT.format(nav=nav_name, map=map_yaml or stem + ".yaml"))
    return path
